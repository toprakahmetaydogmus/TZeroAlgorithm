TOKEN_WARN_THRESHOLD = 8000  # Tokens (~32,000 characters)


class GitSecurityGuard:
    """Enterprise pre-commit guard ensuring zero secret leaks and optimal prompt tokens."""

    _TZERO_MARKER = "T-Zero Git Pre-Commit"

    @classmethod
    def install_hook(cls, repo_dir: str = ".") -> Dict[str, Any]:
        """Installs pre-commit hook into target repository while preserving existing hooks."""
        abs_repo = os.path.abspath(repo_dir)
        git_dir = os.path.join(abs_repo, ".git")

        if not os.path.isdir(git_dir):
            return {
                "success": False,
                "message": f"Target path '{repo_dir}' is not a git repository (missing .git directory)."
            }

        hooks_dir = os.path.join(git_dir, "hooks")
        os.makedirs(hooks_dir, exist_ok=True)

        hook_path = os.path.join(hooks_dir, "pre-commit")
        backup_path = os.path.join(hooks_dir, "pre-commit.user-backup")
        bat_path = os.path.join(hooks_dir, "pre-commit.bat")
        bat_backup = os.path.join(hooks_dir, "pre-commit.bat.user-backup")

        try:
            # Preserve pre-existing non-T-Zero Unix pre-commit hook cleanly
            if os.path.isfile(hook_path):
                with open(hook_path, "r", encoding="utf-8", errors="ignore") as f:
                    existing = f.read()
                if cls._TZERO_MARKER not in existing and not os.path.exists(backup_path):
                    with open(backup_path, "w", encoding="utf-8", newline="\n") as bf:
                        bf.write(existing)
                    try:
                        st_b = os.stat(hook_path)
                        os.chmod(backup_path, st_b.st_mode | stat.S_IEXEC)
                    except Exception:
                        pass

            # Preserve pre-existing non-T-Zero Windows batch hook cleanly
            if os.path.isfile(bat_path):
                with open(bat_path, "r", encoding="utf-8", errors="ignore") as f:
                    existing_bat = f.read()
                if cls._TZERO_MARKER not in existing_bat and not os.path.exists(bat_backup):
                    with open(bat_backup, "w", encoding="utf-8") as bf:
                        bf.write(existing_bat)

            hook_script = f"""#!/bin/sh
# {cls._TZERO_MARKER} & Token Guard
# Auto-generated by Siber Akademi T-Zero Context Architect
HOOK_DIR="$(dirname "$0")"
if [ -f "$HOOK_DIR/pre-commit.user-backup" ]; then
    sh "$HOOK_DIR/pre-commit.user-backup" "$@"
    USER_EXIT=$?
    if [ $USER_EXIT -ne 0 ]; then
        exit $USER_EXIT
    fi
fi

python -c "try:
    from tzero.tzero_guard import GitSecurityGuard
except ImportError:
    import tzero_guard; GitSecurityGuard = tzero_guard.GitSecurityGuard
import sys; sys.exit(GitSecurityGuard.run_cli_check('.'))"
EXIT_CODE=$?

if [ $EXIT_CODE -ne 0 ]; then
    echo "\\033[31m[T-ZERO GUARD BLOCKED COMMIT] Commit aborted due to secret leaks or scan errors.\\033[0m"
    exit 1
fi

exit 0
"""
            with open(hook_path, "w", encoding="utf-8", newline="\n") as f:
                f.write(hook_script)

            try:
                st = os.stat(hook_path)
                os.chmod(hook_path, st.st_mode | stat.S_IEXEC | stat.S_IXGRP | stat.S_IXOTH)
            except Exception:
                pass

            bat_script = f"""@echo off
REM {cls._TZERO_MARKER} for Windows
if exist "%~dp0pre-commit.bat.user-backup" (
    call "%~dp0pre-commit.bat.user-backup" %*
    if %ERRORLEVEL% NEQ 0 exit /b %ERRORLEVEL%
)
python -c "try:^
    from tzero.tzero_guard import GitSecurityGuard^
except ImportError:^
    import tzero_guard; GitSecurityGuard = tzero_guard.GitSecurityGuard^
import sys; sys.exit(GitSecurityGuard.run_cli_check('.'))"
if %ERRORLEVEL% NEQ 0 (
    echo [T-ZERO GUARD BLOCKED COMMIT] Commit aborted due to secret leaks or scan errors.
    exit /b 1
)
exit /b 0
"""
            with open(bat_path, "w", encoding="utf-8") as f:
                f.write(bat_script)

            return {
                "success": True,
                "hook_path": hook_path,
                "bat_path": bat_path,
                "preserved_existing": os.path.isfile(backup_path) or os.path.isfile(bat_backup),
                "message": f"Successfully installed T-Zero Pre-Commit Guard in {hook_path}"
            }
        except Exception as e:
            return {
                "success": False,
                "message": f"Failed to write hook file: {e}"
            }

    @classmethod
    def uninstall_hook(cls, repo_dir: str = ".") -> Dict[str, Any]:
        """Uninstalls T-Zero pre-commit hook and restores any backed-up user hook cleanly."""
        hooks_dir = os.path.join(os.path.abspath(repo_dir), ".git", "hooks")
        if not os.path.isdir(hooks_dir):
            return {"success": False, "message": "Missing .git/hooks directory."}
        for main_name, bak_name in (("pre-commit", "pre-commit.user-backup"), ("pre-commit.bat", "pre-commit.bat.user-backup")):
            main_p = os.path.join(hooks_dir, main_name)
            bak_p = os.path.join(hooks_dir, bak_name)
            is_tzero_hook = False
            if os.path.isfile(main_p):
                with open(main_p, "r", encoding="utf-8", errors="ignore") as f:
                    is_tzero_hook = cls._TZERO_MARKER in f.read()
                if is_tzero_hook:
                    os.remove(main_p)
            if os.path.isfile(bak_p):
                os.replace(bak_p, main_p)
        return {"success": True, "message": "Uninstalled T-Zero Pre-Commit Guard and restored prior hooks."}

    @classmethod
    def scan_staged_content(
        cls,
        files_map: Dict[str, str],
        total_input: Optional[int] = None,
        skipped_files: Optional[List[str]] = None,
        errored_files: Optional[List[str]] = None,
    ) -> Dict[str, Any]:
        """Scans in-memory staged files map {filename: content} for secrets and token bloat."""
        violations = []
        warnings = []
        err_list = list(errored_files or [])
        skip_list = list(skipped_files or [])

        for filename, content in files_map.items():
            findings = ZeroLeakEngine.scan_text(content, check_entropy=True)
            for f in findings:
                violations.append({
                    "file": filename,
                    "type": f"{f.provider}: {f.description}",
                    "match_count": 1,
                    "line": f.line_no,
                    "preview": f.preview,
                    "entropy": f.entropy
                })

            approx_tokens = max(1, len(content) // 4)
            if approx_tokens > TOKEN_WARN_THRESHOLD:
                warnings.append(
                    f"File '{filename}' has {approx_tokens:,} tokens. Consider compressing with T-Zero before committing."
                )

        clean = (len(violations) == 0 and len(err_list) == 0)
        return {
            "clean": clean,
            "violations": violations,
            "warnings": warnings,
            "errors": err_list,
            "skipped": skip_list,
            "files_input": total_input if total_input is not None else len(files_map) + len(skip_list) + len(err_list),
            "files_scanned": len(files_map),
            "files_skipped": len(skip_list),
            "files_errored": len(err_list),
        }

    @classmethod
    def scan_directory(cls, repo_dir: str = ".") -> Dict[str, Any]:
        """Scans all repository files for hardcoded secrets, keys, and credentials."""
        abs_repo = os.path.abspath(repo_dir)
        files_map: Dict[str, str] = {}
        skipped_files: List[str] = []
        errored_files: List[str] = []
        skip_dirs = {".git", "__pycache__", ".pytest_cache", "target", "dist", "build", ".venv", "venv", ".egg-info", "node_modules"}
        skip_files = {
            "package-lock.json", "yarn.lock", "pnpm-lock.yaml", "Cargo.lock",
            "poetry.lock", "composer.lock", "Gemfile.lock", "Pipfile.lock"
        }
        code_exts = {".py", ".rs", ".js", ".ts", ".jsx", ".tsx", ".go", ".java", ".json", ".toml", ".yaml", ".yml", ".env", ".sh", ".ps1", ".cfg", ".ini"}
        total_seen = 0

        for root, dirs, files in os.walk(abs_repo):
            dirs[:] = [d for d in dirs if d not in skip_dirs]
            for f in files:
                if f in skip_files or f.endswith((".lock", ".min.js", ".min.css", ".map")):
                    continue
                _, ext = os.path.splitext(f)
                if ext.lower() in code_exts or f.startswith(".env"):
                    total_seen += 1
                    fpath = os.path.join(root, f)
                    rel_path = os.path.relpath(fpath, abs_repo).replace("\\", "/")
                    if f.startswith(".env") and f != ".env.example":
                        try:
                            check = subprocess.run(["git", "-C", abs_repo, "check-ignore", fpath], capture_output=True)
                            if check.returncode == 0:
                                skipped_files.append(rel_path)
                                continue
                        except Exception:
                            pass
                    try:
                        with open(fpath, "r", encoding="utf-8", errors="strict") as fp:
                            files_map[rel_path] = fp.read()
                    except UnicodeDecodeError:
                        try:
                            with open(fpath, "r", encoding="utf-8", errors="replace") as fp:
                                files_map[rel_path] = fp.read()
                        except Exception as exc:
                            errored_files.append(f"{rel_path}: {exc}")
                    except Exception as exc:
                        errored_files.append(f"{rel_path}: {exc}")
        return cls.scan_staged_content(
            files_map, total_input=total_seen, skipped_files=skipped_files, errored_files=errored_files
        )

    @classmethod
    def run_cli_check(cls, repo_dir: str = ".") -> int:
        """Executes pre-commit check on currently staged git files."""
        abs_repo = os.path.abspath(repo_dir)
        git_dir = os.path.join(abs_repo, ".git")
        try:
            proc = subprocess.run(
                ["git", "-C", abs_repo, "diff", "--cached", "--name-only"],
                capture_output=True, text=True, check=False,
            )
        except Exception as exc:
            print(f"[T-ZERO GUARD ERROR] Unable to execute git diff: {exc}", file=sys.stderr)
            return 1

        if proc.returncode != 0:
            err_msg = (proc.stderr or proc.stdout or "git diff --cached failed").strip()
            print(f"[T-ZERO GUARD ERROR] Staged file listing failed ({git_dir}): {err_msg}", file=sys.stderr)
            return 1

        staged_names = [line.strip() for line in proc.stdout.splitlines() if line.strip()]
        if not staged_names:
            return 0

        files_map: Dict[str, str] = {}
        skipped_files: List[str] = []
        errored_files: List[str] = []
        for fname in staged_names:
            if fname.startswith(".agents/"):
                skipped_files.append(fname)
                continue
            show_proc = subprocess.run(
                ["git", "-C", abs_repo, "show", f":{fname}"],
                capture_output=True,
                check=False,
            )
            if show_proc.returncode != 0:
                err_txt = show_proc.stderr.decode("utf-8", errors="replace").strip()
                errored_files.append(f"{fname}: git show failed ({err_txt})")
                continue
            raw_bytes = show_proc.stdout
            if b"\x00" in raw_bytes[:4096]:
                skipped_files.append(fname)
                continue
            files_map[fname] = raw_bytes.decode("utf-8", errors="replace")

        res = cls.scan_staged_content(
            files_map,
            total_input=len(staged_names),
            skipped_files=skipped_files,
            errored_files=errored_files,
        )

        if not res["clean"]:
            print("\n" + "=" * 70)
            print("🚨 \033[31mT-ZERO ZERO-LEAK SECURITY GUARD: COMMIT BLOCKED!\033[0m")
            print("=" * 70)
            if res["errors"]:
                print("Unreadable or failed staged files:")
                for err in res["errors"]:
                    print(f"  ❌ {err}")
            if res["violations"]:
                print("Found prohibited credentials / hardcoded secrets in staged files:")
                for v in res["violations"]:
                    print(f"  ❌ \033[33m{v['file']}\033[0m (Line {v['line']}): Detected {v['type']}")
            print(f"\nCounts: input={res['files_input']} scanned={res['files_scanned']} skipped={res['files_skipped']} errored={res['files_errored']}")
            print("=" * 70 + "\n")
            return 1

        if res["warnings"]:
            print("\n⚠️  [T-Zero Token Optimization Notice]")
            for w in res["warnings"]:
                print(f"  • {w}")

        print(f"⚡ \033[32m[T-Zero Pre-Commit Guard] Scanned {res['files_scanned']}/{res['files_input']} staged files cleanly.\033[0m")
        return 0


def main():
    target = sys.argv[1] if len(sys.argv) > 1 else "."
    sys.exit(GitSecurityGuard.run_cli_check(target))


if __name__ == "__main__":
    main()

