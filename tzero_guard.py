"""T-Zero Git Pre-Commit Zero-Leak & Token Security Guard.

Automatically intercepts git commits, scanning staged files for:
1. Zero-Leak Security: Blocks accidental commits of API keys, tokens, private keys, passwords.
2. Token Bloat Alert: Warns when uncompressed staged files exceed recommended token thresholds.
3. Micro-Patch companion suggestion.

Developer: Toprak Ahmet Aydoğmuş (Siber Akademi)
Part of T-Zero Context Architect v7.0.0 Master Edition.
"""

import os
import re
import sys
import stat
import subprocess
from typing import Dict, List, Any, Optional

SECRET_PATTERNS = [
    ("OpenAI / AI Key", re.compile(r"\b(sk-[a-zA-Z0-9_\-]{20,})\b")),
    ("GitHub Personal Token", re.compile(r"\b(ghp_[a-zA-Z0-9]{36})\b")),
    ("GitHub OAuth Token", re.compile(r"\b(gho_[a-zA-Z0-9]{36})\b")),
    ("AWS Access Key", re.compile(r"\b(AKIA[0-9A-Z]{16})\b")),
    ("Private Key Header", re.compile(r"-----BEGIN (?:RSA |EC |OPENSSH )?PRIVATE KEY-----")),
    ("Hardcoded API Secret", re.compile(r"(?:api_key|apikey|secret_key|app_secret)\s*[:=]\s*['\"][a-zA-Z0-9_\-]{16,}['\"]", re.IGNORECASE)),
    ("Hardcoded Password", re.compile(r"(?:password|user_pass|db_pass)\s*[:=]\s*['\"][^'\"]{6,}['\"]", re.IGNORECASE)),
]

TOKEN_WARN_THRESHOLD = 8000  # Tokens (~32,000 characters)


class GitSecurityGuard:
    """Enterprise pre-commit guard ensuring zero secret leaks and optimal prompt tokens."""

    @classmethod
    def install_hook(cls, repo_dir: str = ".") -> Dict[str, Any]:
        """Installs pre-commit hook into target repository's .git/hooks directory."""
        abs_repo = os.path.abspath(repo_dir)
        git_dir = os.path.join(abs_repo, ".git")

        if not os.path.isdir(git_dir):
            return {
                "success": False,
                "message": f"Target path '{repo_dir}' is not a git repository (missing .git directory)."
            }

        hooks_dir = os.path.join(git_dir, "hooks")
        os.makedirs(hooks_dir, exist_ok=True)

        hook_path = os.path.join(hooks_dir, "pre-commit")
        hook_script = f"""#!/bin/sh
# T-Zero Git Pre-Commit Zero-Leak & Token Guard
# Auto-generated by Siber Akademi T-Zero Context Architect

python -c "import tzero_guard; import sys; sys.exit(tzero_guard.GitSecurityGuard.run_cli_check('.'))"
EXIT_CODE=$?

if [ $EXIT_CODE -ne 0 ]; then
    echo "\\033[31m[T-ZERO GUARD BLOCKED COMMIT] Commit aborted due to secret leaks or policy violations.\\033[0m"
    exit 1
fi

exit 0
"""

        try:
            with open(hook_path, "w", encoding="utf-8", newline="\n") as f:
                f.write(hook_script)

            # Mark executable on Unix/Mac
            try:
                st = os.stat(hook_path)
                os.chmod(hook_path, st.st_mode | stat.S_IEXEC | stat.S_IXGRP | stat.S_IXOTH)
            except Exception:
                pass

            # Also create pre-commit.bat for native Windows cmd / powershell hooks
            bat_path = os.path.join(hooks_dir, "pre-commit.bat")
            bat_script = f"""@echo off
REM T-Zero Git Pre-Commit Guard for Windows
python -c "import tzero_guard; import sys; sys.exit(tzero_guard.GitSecurityGuard.run_cli_check('.'))"
if %ERRORLEVEL% NEQ 0 (
    echo [T-ZERO GUARD BLOCKED COMMIT] Commit aborted due to secret leaks.
    exit /b 1
)
exit /b 0
"""
            with open(bat_path, "w", encoding="utf-8") as f:
                f.write(bat_script)

            return {
                "success": True,
                "hook_path": hook_path,
                "bat_path": bat_path,
                "message": f"Successfully installed T-Zero Pre-Commit Guard in {hook_path}"
            }
        except Exception as e:
            return {
                "success": False,
                "message": f"Failed to write hook file: {e}"
            }

    @classmethod
    def scan_staged_content(cls, files_map: Dict[str, str]) -> Dict[str, Any]:
        """Scans in-memory staged files map {filename: content} for secrets and token bloat."""
        violations = []
        warnings = []

        placeholder_markers = (
            "DEMO", "MOCK", "EXAMPLE", "YOUR-", "YOUR_", "ENTER_YOUR",
            "PLACEHOLDER", "000000000000", "1234567890", "TEST_KEY", "DUMMY", "SAMPLE"
        )

        for filename, content in files_map.items():
            # Check secret patterns
            for label, pattern in SECRET_PATTERNS:
                raw_matches = pattern.findall(content)
                real_matches = [
                    m for m in raw_matches
                    if not any(marker in str(m).upper() for marker in placeholder_markers)
                ]
                if real_matches:
                    violations.append({
                        "file": filename,
                        "type": label,
                        "match_count": len(real_matches)
                    })

            # Check token bloat
            approx_tokens = max(1, len(content) // 4)
            if approx_tokens > TOKEN_WARN_THRESHOLD:
                warnings.append(
                    f"File '{filename}' has {approx_tokens:,} tokens. Consider compressing with T-Zero before committing."
                )

        clean = (len(violations) == 0)
        return {
            "clean": clean,
            "violations": violations,
            "warnings": warnings,
            "files_scanned": len(files_map)
        }

    @classmethod
    def scan_directory(cls, repo_dir: str = ".") -> Dict[str, Any]:
        """Scans all repository files for hardcoded secrets, keys, and credentials."""
        abs_repo = os.path.abspath(repo_dir)
        files_map: Dict[str, str] = {}
        skip_dirs = {".git", "__pycache__", ".pytest_cache", "target", "dist", "build", ".venv", "venv", ".egg-info", "node_modules"}
        code_exts = {".py", ".rs", ".js", ".ts", ".jsx", ".tsx", ".go", ".java", ".json", ".toml", ".yaml", ".yml", ".env"}

        for root, dirs, files in os.walk(abs_repo):
            dirs[:] = [d for d in dirs if d not in skip_dirs]
            for f in files:
                _, ext = os.path.splitext(f)
                if ext.lower() in code_exts or f.startswith(".env"):
                    fpath = os.path.join(root, f)
                    rel_path = os.path.relpath(fpath, abs_repo).replace("\\", "/")
                    if "test" in rel_path.lower():
                        continue
                    try:
                        with open(fpath, "r", encoding="utf-8", errors="replace") as fp:
                            files_map[rel_path] = fp.read()
                    except Exception:
                        pass
        return cls.scan_staged_content(files_map)

    @classmethod
    def run_cli_check(cls, repo_dir: str = ".") -> int:
        """Executes pre-commit check on currently staged git files."""
        abs_repo = os.path.abspath(repo_dir)
        try:
            # Get list of staged files
            cmd = ["git", "-C", abs_repo, "diff", "--cached", "--name-only"]
            output = subprocess.check_output(cmd, text=True, stderr=subprocess.DEVNULL)
            staged_names = [line.strip() for line in output.splitlines() if line.strip()]
        except Exception:
            return 0  # Not in a git repo or no git binary

        if not staged_names:
            return 0

        # Read content of staged files from git index
        files_map: Dict[str, str] = {}
        for fname in staged_names:
            try:
                content = subprocess.check_output(
                    ["git", "-C", abs_repo, "show", f":{fname}"],
                    text=True,
                    errors="replace",
                    stderr=subprocess.DEVNULL
                )
                files_map[fname] = content
            except Exception:
                continue

        res = cls.scan_staged_content(files_map)

        if not res["clean"]:
            print("\n" + "=" * 70)
            print("🚨 \033[31mT-ZERO ZERO-LEAK SECURITY GUARD: COMMIT BLOCKED!\033[0m")
            print("=" * 70)
            print("Found prohibited credentials / hardcoded secrets in staged files:")
            for v in res["violations"]:
                print(f"  ❌ \033[33m{v['file']}\033[0m: Detected {v['type']}")
            print("\nRemove all secrets and credentials before committing.")
            print("=" * 70 + "\n")
            return 1

        if res["warnings"]:
            print("\n⚠️  [T-Zero Token Optimization Notice]")
            for w in res["warnings"]:
                print(f"  • {w}")

        print("⚡ \033[32m[T-Zero Pre-Commit Guard] All staged files clean & safe.\033[0m")
        return 0


def main():
    target = sys.argv[1] if len(sys.argv) > 1 else "."
    sys.exit(GitSecurityGuard.run_cli_check(target))


if __name__ == "__main__":
    main()

